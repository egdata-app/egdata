/**
 * Builds one self-contained catalog per locale.
 *
 * `src/locales/<locale>/translation.json` stays the source of truth, but a
 * locale is frequently missing keys that exist in en-US. Paraglide used to
 * fall back to the base locale per message, which meant shipping en-US
 * messages next to every other locale. Here the fallback is baked in at build
 * time instead, so the browser only ever needs the chunk for the active locale.
 *
 * Output: src/i18n/catalogs/<locale>.json (gitignored, compact JSON)
 */
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const SOURCE_LOCALE = "en-US";
const localesDir = path.join(process.cwd(), "src", "locales");
const outDir = path.join(process.cwd(), "src", "i18n", "catalogs");
const translationFile = "translation.json";

function isRecord(value) {
  return !!value && typeof value === "object" && !Array.isArray(value);
}

/** Deep merge where `override` wins; strings and arrays are replaced wholesale. */
function merge(base, override) {
  if (!isRecord(base) || !isRecord(override)) {
    return override === undefined ? base : override;
  }

  const result = { ...base };

  for (const [key, value] of Object.entries(override)) {
    const current = base[key];

    if (isRecord(current) && isRecord(value)) {
      result[key] = merge(current, value);
      continue;
    }

    result[key] = value;
  }

  return result;
}

function countLeaves(value) {
  if (typeof value === "string") return 1;
  if (!isRecord(value)) return 0;

  let total = 0;
  for (const child of Object.values(value)) {
    total += countLeaves(child);
  }

  return total;
}

async function readJson(file) {
  return JSON.parse(await readFile(file, "utf8"));
}

const entries = await readdir(localesDir, { withFileTypes: true });
const locales = entries
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

if (!locales.includes(SOURCE_LOCALE)) {
  console.error(`Missing source locale ${SOURCE_LOCALE} in ${localesDir}`);
  process.exit(1);
}

const source = await readJson(path.join(localesDir, SOURCE_LOCALE, translationFile));

await mkdir(outDir, { recursive: true });

let written = 0;
let unchanged = 0;
let warnings = 0;
let totalBytes = 0;

for (const locale of locales) {
  const raw =
    locale === SOURCE_LOCALE
      ? source
      : await readJson(path.join(localesDir, locale, translationFile));

  const merged = merge(source, raw);
  const serialized = JSON.stringify(merged);
  const target = path.join(outDir, `${locale}.json`);

  totalBytes += Buffer.byteLength(serialized);

  const previous = await readFile(target, "utf8").catch(() => null);

  if (previous === serialized) {
    unchanged += 1;
    continue;
  }

  await writeFile(target, serialized, "utf8");
  written += 1;

  const missing = countLeaves(source) - countLeaves(raw);
  if (missing > 0) warnings += 1;
}

const stale = (await readdir(outDir))
  .filter((file) => file.endsWith(".json"))
  .filter((file) => !locales.includes(file.slice(0, -".json".length)));

for (const file of stale) {
  await rm(path.join(outDir, file), { force: true });
}

/** Builds the server-side locale -> catalog map so it can never drift from src/locales. */
function identifierFor(locale) {
  return `catalog_${locale.replace(/[^a-zA-Z0-9]/g, "_")}`;
}

const mapSource = [
  "// Generated by scripts/build-i18n-catalogs.mjs. Do not edit by hand.",
  'import type { Catalog } from "../catalog";',
  "",
  ...locales.map((locale) => `import ${identifierFor(locale)} from "./${locale}.json";`),
  "",
  "export const catalogs: Record<string, Catalog> = {",
  ...locales.map((locale) => `  ${JSON.stringify(locale)}: ${identifierFor(locale)},`),
  "};",
  "",
  'export const baseCatalog = catalogs["en-US"] as Catalog;',
  "",
].join("\n");

const loadersSource = [
  "// Generated by scripts/build-i18n-catalogs.mjs. Do not edit by hand.",
  "//",
  "// Only dynamic imports live here so the client never bundles every catalog.",
  "// The chunk names keep filenames predictable (`i18n/<locale>.<hash>.js`), which",
  "// is what lets the server modulepreload the active locale's catalog.",
  'import type { Catalog } from "../catalog";',
  "",
  "export const catalogLoaders: Record<string, () => Promise<{ default: Catalog }>> = {",
  ...locales.map(
    (locale) =>
      `  ${JSON.stringify(locale)}: () => import(/* webpackChunkName: "i18n/${locale}" */ "./${locale}.json"),`,
  ),
  "};",
  "",
].join("\n");

const mapPath = path.join(outDir, "index.ts");
const loadersPath = path.join(outDir, "loaders.ts");

if ((await readFile(mapPath, "utf8").catch(() => null)) !== mapSource) {
  await writeFile(mapPath, mapSource, "utf8");
}

if ((await readFile(loadersPath, "utf8").catch(() => null)) !== loadersSource) {
  await writeFile(loadersPath, loadersSource, "utf8");
}

console.log(
  `[i18n] ${locales.length} catalogs (${written} written, ${unchanged} unchanged, ${(
    totalBytes / 1024
  ).toFixed(0)} KB total${warnings ? `, ${warnings} locale(s) filled from ${SOURCE_LOCALE}` : ""})`,
);
